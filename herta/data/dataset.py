Pairing = Literal["exact", "intersection", "none"]
PeakSelection = Literal["most_detected", "detection_variance"]


@dataclass
class MultiomeData:
    """Aligned in-memory scRNA/scATAC contract used across HERTA stages."""

    rna: np.ndarray | sparse.spmatrix
    atac: np.ndarray | sparse.spmatrix
    cell_types: np.ndarray | None
    genes: pd.DataFrame
    peaks: pd.DataFrame
    tf_names: list[str] | None
    motif: np.ndarray | sparse.spmatrix | None
    motif_activity: np.ndarray | None = None
    cell_names: list[str] | None = None


def read_table(path: str | Path) -> pd.DataFrame:
    """Read a CSV, TSV/TXT, or Parquet table from a canonical input path."""

    path = Path(path)
    if path.suffix in {".parquet", ".pq"}:
        return pd.read_parquet(path)
    separator = "\t" if path.suffix in {".tsv", ".txt"} else ","
    return pd.read_csv(path, sep=separator)


def _align_annotation(table: pd.DataFrame, key: str, names: pd.Index) -> pd.DataFrame:
    names = pd.Index(names).astype(str)
    table = table.copy()
    if key not in table:
        if len(table) != len(names):
            raise ValueError(f"{key} annotation length does not match the matrix.")
        table.insert(0, key, names)
        return table.reset_index(drop=True)
    table[key] = table[key].astype(str)
    if table[key].duplicated().any():
        raise ValueError(f"{key} annotation contains duplicate identifiers.")
    missing = names.difference(table[key])
    if len(missing):
        raise ValueError(f"{key} annotation is missing {len(missing)} matrix features.")
    return table.set_index(key).loc[names].reset_index()


def load_toy_data(input_dir: str | Path) -> MultiomeData:
    """Load the compact paired multiome fixture generated by HERTA scripts."""

    input_dir = Path(input_dir)
    arrays = np.load(input_dir / "arrays.npz", allow_pickle=True)
    genes = pd.read_csv(input_dir / "genes.csv")
    peaks = pd.read_csv(input_dir / "peaks.csv")
    tf_names = pd.read_csv(input_dir / "tfs.csv")["gene"].astype(str).tolist()
    motif = arrays["motif"].astype(np.float32)
    if motif.shape == (len(tf_names), len(peaks)):
        motif = motif.T
    if motif.shape != (len(peaks), len(tf_names)):
        raise ValueError("Toy motif matrix must align to peak x TF.")
    return MultiomeData(
        rna=arrays["rna"].astype(np.float32),
        atac=arrays["atac"].astype(np.float32),
        cell_types=arrays["cell_types"].astype(str) if "cell_types" in arrays else None,
        genes=genes,
        peaks=peaks,
        tf_names=tf_names,
        motif=(motif > 0).astype(np.float32),
        motif_activity=arrays.get("motif_activity"),
    )


def load_configured_multiome(config: dict) -> MultiomeData:
    """Load matrices only; this helper does not perform canonical preprocessing.

    Formal HERTA runs must use :func:`prepare_multiome` and forward the returned
    ``metadata["state_factors"]`` to ``build_state_graph``.
    """

    data_cfg = config.get("data", {})
    if data_cfg.get("input_type", "anndata") == "toy":
        return load_toy_data(data_cfg.get("toy_dir", "data/toy"))
    import anndata as ad

    rna = ad.read_h5ad(data_cfg["rna_h5ad"])
    atac = ad.read_h5ad(data_cfg["atac_h5ad"])
    if rna.n_obs != atac.n_obs or not np.array_equal(rna.obs_names, atac.obs_names):
        raise ValueError("RNA and ATAC AnnData objects must contain aligned cells.")
    genes = read_table(data_cfg["gene_annotation"]) if data_cfg.get("gene_annotation") else rna.var.copy()
    peaks = read_table(data_cfg["peak_annotation"]) if data_cfg.get("peak_annotation") else atac.var.copy()
    genes = _align_annotation(genes, "gene", rna.var_names)
    peaks = _align_annotation(peaks, "peak", atac.var_names)
    tf_names = (
        read_table(data_cfg["tf_annotation"])["gene"].astype(str).tolist()
        if data_cfg.get("tf_annotation")
        else []
    )
    label_key = data_cfg.get("cell_type_key")
    labels = rna.obs[label_key].astype(str).to_numpy() if label_key else None
    return MultiomeData(
        rna.X.copy(),
        atac.X.copy(),
        labels,
        genes,
        peaks,
        tf_names,
        None,
        cell_names=rna.obs_names.astype(str).tolist(),
    )


def _check_paths(*paths: str | Path) -> tuple[Path, ...]:
    resolved = tuple(Path(path) for path in paths)
    missing = [path for path in resolved if not path.exists()]
    if missing:
        listing = "\n".join(f"  - {path}" for path in missing)
        raise FileNotFoundError(f"Missing required multiome input file(s):\n{listing}")
    return resolved


def _cell_keys(names: pd.Index, suffix_pattern: str | None) -> pd.Index:
    keys = names.astype(str)
    if suffix_pattern is not None:
        keys = keys.str.replace(suffix_pattern, "", regex=True)
    if keys.has_duplicates:
        raise ValueError("Cell IDs are not unique after applying the suffix pattern.")
    return keys


def _subset_cells(adata: AnnData, n_cells: int | None, random_state: int) -> AnnData:
    if n_cells is None or n_cells >= adata.n_obs:
        return adata
    if n_cells <= 0:
        raise ValueError("`n_cells` must be positive when specified.")
    selected = np.sort(
        np.random.default_rng(random_state).choice(adata.n_obs, size=n_cells, replace=False)
    )
    return adata[selected].copy()


def load_multiome_anndata(
    rna_path: str | Path,
    atac_path: str | Path,
    *,
    pairing: Pairing = "exact",
    rna_suffix_pattern: str | None = None,
    atac_suffix_pattern: str | None = None,
    n_cells: int | None = None,
    n_peaks: int | None = None,
    peak_selection: PeakSelection = "most_detected",
    peak_min_fraction: float = 0.01,
    peak_max_fraction: float = 0.95,
    random_state: int = 1,
) -> tuple[AnnData, AnnData]:
    """Read RNA and ATAC h5ad files and optionally align their cells.

    ``pairing='exact'`` requires identical cell IDs and order.
    ``pairing='intersection'`` aligns the shared IDs after optional modality
    suffix removal.  ``pairing='none'`` supports unpaired datasets and subsets
    each modality independently.
    """

    import anndata as ad

    if pairing not in {"exact", "intersection", "none"}:
        raise ValueError("`pairing` must be 'exact', 'intersection', or 'none'.")
    if peak_selection not in {"most_detected", "detection_variance"}:
        raise ValueError("peak_selection must be 'most_detected' or 'detection_variance'.")
    if not 0 <= peak_min_fraction < peak_max_fraction <= 1:
        raise ValueError("Expected 0 <= peak_min_fraction < peak_max_fraction <= 1.")
    rna_path, atac_path = _check_paths(rna_path, atac_path)
    rna, atac = ad.read_h5ad(rna_path), ad.read_h5ad(atac_path)

    if pairing == "exact":
        if rna.n_obs != atac.n_obs or not np.array_equal(rna.obs_names, atac.obs_names):
            raise ValueError(
                "Exact pairing requires RNA and ATAC to have identical obs_names in the same order. "
                "Use pairing='intersection' or pairing='none' when appropriate."
            )
    elif pairing == "intersection":
        rna_keys = _cell_keys(rna.obs_names, rna_suffix_pattern)
        atac_keys = _cell_keys(atac.obs_names, atac_suffix_pattern)
        common = rna_keys.intersection(atac_keys, sort=False)
        if common.empty:
            raise ValueError("RNA and ATAC have no shared cell IDs after cell-ID normalization.")
        rna_pos = pd.Series(np.arange(rna.n_obs), index=rna_keys).loc[common].to_numpy()
        atac_pos = pd.Series(np.arange(atac.n_obs), index=atac_keys).loc[common].to_numpy()
        rna, atac = rna[rna_pos].copy(), atac[atac_pos].copy()
        rna.obs["original_cell_name"] = rna.obs_names.astype(str)
        atac.obs["original_cell_name"] = atac.obs_names.astype(str)
        rna.obs_names = common.copy()
        atac.obs_names = common.copy()

    if pairing == "none":
        rna = _subset_cells(rna, n_cells, random_state)
        atac = _subset_cells(atac, n_cells, random_state)
    elif n_cells is not None and n_cells < rna.n_obs:
        if n_cells <= 0:
            raise ValueError("`n_cells` must be positive when specified.")
        selected = np.sort(
            np.random.default_rng(random_state).choice(rna.n_obs, size=n_cells, replace=False)
        )
        rna, atac = rna[selected].copy(), atac[selected].copy()

    if n_peaks is not None and n_peaks < atac.n_vars:
        if n_peaks <= 0:
            raise ValueError("`n_peaks` must be positive when specified.")
        detected = (
            atac.X.getnnz(axis=0)
            if sparse.issparse(atac.X)
            else np.asarray((np.asarray(atac.X) > 0).sum(axis=0)).ravel()
        )
        detected = np.asarray(detected).ravel()
        detection_rate = detected / max(atac.n_obs, 1)
        atac.var["detection_rate"] = detection_rate
        if peak_selection == "detection_variance":
            score = detection_rate * (1.0 - detection_rate)
            candidates = np.flatnonzero(
                (detection_rate >= peak_min_fraction)
                & (detection_rate <= peak_max_fraction)
            )
            if candidates.size == 0:
                raise ValueError("No ATAC peaks pass the detection-rate thresholds.")
            selected = candidates[np.argsort(score[candidates], kind="stable")[-n_peaks:]]
            atac.var["variability_score"] = score
        else:
            selected = np.argsort(detected, kind="stable")[-n_peaks:]
        selected = np.sort(selected)
        atac = atac[:, selected].copy()
    return rna, atac


def _gene_table(rna: AnnData) -> pd.DataFrame:
    genes = rna.var.copy()
    if "name" in genes:
        genes["annotation_name"] = genes["name"]
        genes = genes.drop(columns="name")
    genes.insert(0, "gene", rna.var_names.astype(str))
    genes["name"] = genes["gene"]
    if "strand" in genes:
        positive = genes["strand"].astype(str) == "+"
        genes["tss"] = np.where(positive, genes["chromStart"], genes["chromEnd"] - 1)
    return genes.reset_index(drop=True)


def _peak_table(atac: AnnData) -> pd.DataFrame:
    peaks = atac.var.copy()
    peaks.insert(0, "peak", atac.var_names.astype(str))
    return peaks.reset_index(drop=True)


def _motif_matrix(peak_tf: pd.DataFrame, peaks: pd.Index, tfs: pd.Index) -> sparse.csr_matrix:
    """Return the authoritative binary peak-by-TF JASPAR matrix."""

    peak_index = pd.Series(np.arange(len(peaks)), index=peaks.astype(str))
    tf_index = pd.Series(np.arange(len(tfs)), index=tfs.astype(str))
    if peak_tf.empty:
        return sparse.csr_matrix((len(peaks), len(tfs)), dtype=np.float32)
    rows = peak_tf["peak"].astype(str).map(peak_index).to_numpy(dtype=int)
    cols = peak_tf["tf"].astype(str).map(tf_index).to_numpy(dtype=int)
    matrix = sparse.coo_matrix(
        (np.ones(len(peak_tf), dtype=np.float32), (rows, cols)),
        shape=(len(peaks), len(tfs)),
    ).tocsr()
    matrix.data.fill(1.0)
    return matrix


def _select_gene_universe(
    rna: AnnData,
    eligible_tfs: pd.Index,
    n_genes: int,
) -> list[str]:
    """Return up to ``n_genes`` HVGs union every eligible TF.

    The HVG budget is resolved before the TF union, so a non-HVG TF never
    displaces an HVG. RNA feature order is retained for stable node IDs.
    """

    if n_genes <= 0:
        raise ValueError("`n_genes` must be positive.")
    eligible_tfs = pd.Index(eligible_tfs).astype(str)
    missing = eligible_tfs.difference(rna.var_names.astype(str), sort=False)
    if len(missing):
        raise ValueError("Eligible TFs must be members of the RNA gene universe.")
    highly_variable = pd.Index(rna.var_names[
        np.asarray(rna.var["highly_variable"], dtype=bool)
    ].astype(str))[: int(n_genes)]
    selected = set(highly_variable).union(eligible_tfs)
    return [str(gene) for gene in rna.var_names.astype(str) if str(gene) in selected]


def _positive_nnz(matrix: object) -> int:
    if sparse.issparse(matrix):
        return int((sparse.csr_matrix(matrix) > 0).nnz)
    return int(np.count_nonzero(np.asarray(matrix) > 0))


def _peak_union_audit(
    *,
    n_input_peaks: int,
    n_coordinate_valid: int,
    n_support_pass: int,
    variable: np.ndarray,
    guidance: np.ndarray,
    motif: np.ndarray,
    retained: np.ndarray,
    n_cells: int,
    cell_peak_nnz_before: int,
    cell_peak_nnz_after: int,
) -> dict[str, int | float]:
    return {
        "n_input_peaks": int(n_input_peaks),
        "n_coordinate_valid": int(n_coordinate_valid),
        "n_support_pass": int(n_support_pass),
        "n_variable": int(variable.sum()),
        "n_hvg_guidance": int(guidance.sum()),
        "n_tf_motif": int(motif.sum()),
        "n_variable_hvg_guidance_overlap": int((variable & guidance).sum()),
        "n_variable_tf_motif_overlap": int((variable & motif).sum()),
        "n_hvg_guidance_tf_motif_overlap": int((guidance & motif).sum()),
        "n_triple_overlap": int((variable & guidance & motif).sum()),
        "n_retained_union": int(retained.sum()),
        "retained_fraction_of_qc": float(retained.mean()),
        "cell_peak_nnz_before": int(cell_peak_nnz_before),
        "cell_peak_nnz_after": int(cell_peak_nnz_after),
        "mean_cell_peak_degree_after": float(cell_peak_nnz_after / max(n_cells, 1)),
    }


def prepare_multiome(
    rna_path: str | Path | AnnData,
    atac_path: str | Path | AnnData,
    gtf_path: str | Path,
    motif_bed_path: str | Path,
    *,
    genome_build: str | None = None,
    motif_source_version: str = "JASPAR",
    pairing: Pairing = "exact",
    rna_suffix_pattern: str | None = None,
    atac_suffix_pattern: str | None = None,
    gtf_by: str = "gene_name",
    cell_type_key: str | None = "cell_type",
    n_cells: int | None = None,
    n_hvg: int = 2000,
    rna_hvg_flavor: str = "seurat_v3",
    n_genes: int = 2000,
    n_tfs: int | None = None,
    n_peaks: int | None = None,
    peak_selection: PeakSelection = "detection_variance",
    peak_min_fraction: float = 0.01,
    peak_max_fraction: float = 0.95,
    n_rna_components: int = 256,
    n_atac_components: int = 256,
    n_iter: int = 20,
    drop_first_lsi: bool = True,
    peak_filter_enabled: bool = True,
    peak_min_cells_floor: int = 5,
    peak_min_cell_fraction: float = 0.001,
    n_variable_peaks: int | None = 10_000,
    variable_include_first_component: bool = True,
    retain_hvg_guidance: bool = False,
    retain_tf_motif: bool = False,
    refit_lsi_after_union: bool = True,
    compute_neighbors: bool = False,
    compute_umap: bool = False,
    gene_region: str = "combined",
    promoter_len: int = 2000,
    extend_range: int = 0,
    max_genes_per_peak: int | None = None,
    build_regulatory_candidates: bool = True,
    motif_tf_names: Sequence[str] | None = None,
    random_state: int = 1,
) -> tuple[MultiomeData, dict[str, object]]:
    """Prepare general paired scRNA/scATAC inputs for HERTA.

    ``rna_path`` and ``atac_path`` may be h5ad paths or already loaded,
    identically ordered :class:`~anndata.AnnData` objects.  The in-memory mode
    is intended for inspectable tutorials and avoids reading large files a
    second time after pairing.  Scanpy is used directly for RNA preprocessing.
    LSI, GTF/BED parsing and
    regulatory priors use HERTA-native equivalents of the corresponding
    scGLUE utilities. RNA PCA and ATAC LSI are fitted on all paired cells
    before the optional ``n_cells`` training subset is selected. Raw count matrices are retained in ``MultiomeData``;
    processed AnnData objects, canonical ``state_factors``, and inspectable
    prior tables are returned in the metadata dictionary. Downstream graph
    construction must forward those factors and never refit them. In canonical
    mode, ATAC peaks pass coordinate/support
    QC and a provisional LSI supplies the top variable peaks. Motif overlap and
    peak-gene distance never affect this peak-universe selection.
    """

    if pairing == "none":
        raise ValueError("HERTA MultiomeData requires paired cells; use load_multiome_anndata for unpaired data.")
    if genome_build is None or not str(genome_build).strip():
        raise ValueError("prepare_multiome requires an explicit genome_build.")
    if n_cells is not None and n_cells <= 0:
        raise ValueError("`n_cells` must be positive when specified.")
    if n_variable_peaks is not None and n_variable_peaks < 2:
        raise ValueError("`n_variable_peaks` must be at least two when specified.")
    if n_peaks is not None and n_peaks < 2:
        raise ValueError("`n_peaks` must be at least two when specified.")
    if peak_selection != "detection_variance":
        raise ValueError(
            "Canonical prepare_multiome peak selection is fixed to "
            "'detection_variance'; LSI/prior-based Stage-1 selection is disabled."
        )
    if retain_hvg_guidance or retain_tf_motif:
        warnings.warn(
            "`retain_hvg_guidance` and `retain_tf_motif` are deprecated and ignored: "
            "the minimal peak universe is selected only by coordinate/support QC "
            "and ATAC detection variability.",
            FutureWarning,
            stacklevel=2,
        )
    _check_paths(gtf_path, motif_bed_path)
    in_memory = isinstance(rna_path, AnnData) or isinstance(atac_path, AnnData)
    if in_memory:
        if not isinstance(rna_path, AnnData) or not isinstance(atac_path, AnnData):
            raise TypeError("RNA and ATAC inputs must both be paths or both be AnnData objects.")
        if pairing != "exact":
            raise ValueError(
                "In-memory AnnData inputs must already be paired and use pairing='exact'. "
                "Call load_multiome_anndata first when cell IDs require normalization."
            )
        if rna_path.n_obs != atac_path.n_obs or not np.array_equal(
            rna_path.obs_names, atac_path.obs_names
        ):
            raise ValueError(
                "In-memory RNA and ATAC AnnData objects must have identical obs_names "
                "in the same order."
            )
        rna, atac = rna_path.copy(), atac_path.copy()
    else:
        rna, atac = load_multiome_anndata(
            rna_path,
            atac_path,
            pairing=pairing,
            rna_suffix_pattern=rna_suffix_pattern,
            atac_suffix_pattern=atac_suffix_pattern,
            n_cells=None,
            n_peaks=None,
            peak_selection="detection_variance",
            peak_min_fraction=peak_min_fraction,
            peak_max_fraction=peak_max_fraction,
            random_state=random_state,
        )
    if cell_type_key is not None and cell_type_key not in rna.obs:
        raise KeyError(f"RNA obs does not contain cell-type column '{cell_type_key}'.")

    get_gene_annotation(
        rna,
        gtf=gtf_path,
        gtf_by=gtf_by,
        genome_build=genome_build,
        require_genome_build=True,
    )
    n_input_genes = int(rna.n_vars)
    n_input_peaks = int(atac.n_vars)
    cell_peak_nnz_before = _positive_nnz(atac.X)
    parse_peak_coordinates(
        atac,
        genome_build=genome_build,
        require_genome_build=True,
        drop_invalid=peak_filter_enabled,
    )
    n_coordinate_valid = int(atac.n_vars)
    preprocess_rna(
        rna,
        n_top_genes=min(n_hvg, rna.n_vars),
        hvg_flavor=rna_hvg_flavor,
        n_comps=n_rna_components,
        random_state=random_state,
    )
    if motif_tf_names is not None:
        if build_regulatory_candidates:
            raise ValueError(
                "motif_tf_names can be used only when regulatory candidates are disabled; "
                "TF-peak construction requires motif genomic intervals."
            )
        unique_tf_names = pd.Index(motif_tf_names, dtype=str).drop_duplicates()
        if unique_tf_names.empty:
            raise ValueError("motif_tf_names must contain at least one TF name.")
        motif_bed = pd.DataFrame(
            {
                "tf": unique_tf_names,
                "motif_id_or_site_id": unique_tf_names,
            }
        )
    else:
        motif_bed = load_jaspar_motifs(
            motif_bed_path,
            genome_build=genome_build,
            source_version=motif_source_version,
        )
    tf_table = extract_tf_list(motif_bed, rna)
    eligible_tfs = extract_eligible_tfs(motif_bed, rna)
    if n_tfs is not None:
        warnings.warn(
            "`n_tfs` is deprecated and ignored: HERTA retains every motif-supported "
            "TF that overlaps the RNA gene universe.",
            FutureWarning,
            stacklevel=2,
        )
    if eligible_tfs.empty:
        raise ValueError("No motif TF names overlap RNA feature names.")
    selected_genes = _select_gene_universe(rna, eligible_tfs, n_genes)

    peak_filter_audit: dict[str, object]
    hvg_gene_peak = pd.DataFrame(columns=["gene", "peak", "dist", "weight", "sign"])
    if peak_filter_enabled:
        support_audit = filter_low_support_peaks(
            atac,
            min_cells_floor=peak_min_cells_floor,
            min_cell_fraction=peak_min_cell_fraction,
        )
        requested_peak_budget = 10_000 if n_variable_peaks is None else int(n_variable_peaks)
        if n_peaks is not None:
            requested_peak_budget = min(requested_peak_budget, int(n_peaks))
        resolved_n_variable_peaks = min(requested_peak_budget, atac.n_vars)
        highly_variable_peaks(
            atac,
            min_fraction=0.0,
            max_fraction=1.0,
            n_top_peaks=resolved_n_variable_peaks,
            selection_method="detection_variance",
        )
        variable_mask = np.asarray(atac.var["highly_variable"], dtype=bool)
        atac.var["variable_peak"] = variable_mask

        guidance_mask = np.zeros(atac.n_vars, dtype=bool)
        motif_mask = np.zeros(atac.n_vars, dtype=bool)
        retained_mask = variable_mask
        if not bool(retained_mask.any()):
            raise ValueError("The minimal variable-peak universe is empty.")
        atac.var["hvg_guidance_reachable"] = guidance_mask
        atac.var["tf_motif_supported"] = motif_mask
        atac.var["retained_peak"] = retained_mask
        reasons = np.full(atac.n_vars, "", dtype=object)
        reasons[variable_mask] = "variable"
        atac.var["retention_reason"] = reasons

        retained_nnz = _positive_nnz(atac.X[:, retained_mask])
        peak_filter_audit = {
            **support_audit,
            **_peak_union_audit(
                n_input_peaks=n_input_peaks,
                n_coordinate_valid=n_coordinate_valid,
                n_support_pass=atac.n_vars,
                variable=variable_mask,
                guidance=guidance_mask,
                motif=motif_mask,
                retained=retained_mask,
                n_cells=atac.n_obs,
                cell_peak_nnz_before=cell_peak_nnz_before,
                cell_peak_nnz_after=retained_nnz,
            ),
            "enabled": True,
            "selection_contract": "coordinate_support_qc_then_detection_variability",
            "n_variable_peaks_requested": int(requested_peak_budget),
            "n_variable_peaks_resolved": int(resolved_n_variable_peaks),
            "variable_include_first_component": variable_include_first_component,
            "retain_hvg_guidance": False,
            "retain_tf_motif": False,
            "refit_lsi_after_union": False,
            "input_peak_cap": n_peaks,
        }
        atac = atac[:, retained_mask].copy()
        peak_filter_audit["refit_lsi_performed"] = False
        peak_filter_audit["lsi_fit_count"] = 1
        lsi(
            atac,
            n_components=n_atac_components,
            use_highly_variable=False,
            n_iter=n_iter,
            binarize=False,
            store_loadings=True,
            drop_first_component=drop_first_lsi,
            random_state=random_state,
        )
        atac.var["highly_variable"] = True
        atac.uns["herta_preprocessing"] = {
            **atac.uns.get("herta_preprocessing", {}),
            "peak_filter": peak_filter_audit,
        }
    else:
        lsi(
            atac,
            n_components=n_atac_components,
            use_highly_variable=False,
            n_iter=n_iter,
            binarize=False,
            store_loadings=True,
            drop_first_component=drop_first_lsi,
            random_state=random_state,
        )
        atac.var["coordinate_valid"] = True
        atac.var["low_support_pass"] = True
        atac.var["variable_peak"] = True
        atac.var["hvg_guidance_reachable"] = False
        atac.var["tf_motif_supported"] = False
        atac.var["retained_peak"] = True
        atac.var["retention_reason"] = "filter_disabled"
        peak_filter_audit = {
            "enabled": False,
            "n_input_peaks": n_input_peaks,
            "n_coordinate_valid": n_coordinate_valid,
            "n_support_pass": int(atac.n_vars),
            "n_retained_union": int(atac.n_vars),
            "cell_peak_nnz_before": cell_peak_nnz_before,
            "cell_peak_nnz_after": _positive_nnz(atac.X),
            "mean_cell_peak_degree_after": float(_positive_nnz(atac.X) / atac.n_obs),
            "input_peak_cap": n_peaks,
            "lsi_fit_count": 1,
        }

    if n_cells is not None and n_cells < rna.n_obs:
        peak_filter_audit["selection_fit_n_cells"] = int(atac.n_obs)
        peak_filter_audit["cell_peak_nnz_after_before_cell_subsample"] = int(
            peak_filter_audit["cell_peak_nnz_after"]
        )
        selected = np.sort(
            np.random.default_rng(random_state).choice(rna.n_obs, size=n_cells, replace=False)
        )
        rna, atac = rna[selected].copy(), atac[selected].copy()
        final_nnz = _positive_nnz(atac.X)
        peak_filter_audit["cell_peak_nnz_after"] = final_nnz
        peak_filter_audit["mean_cell_peak_degree_after"] = float(final_nnz / atac.n_obs)

    if compute_neighbors or compute_umap:
        import scanpy as sc

        sc.pp.neighbors(rna, use_rep="X_pca", metric="cosine")
        sc.pp.neighbors(atac, use_rep="X_lsi", metric="cosine")
        if compute_umap:
            sc.tl.umap(rna)
            sc.tl.umap(atac)

    rna_selected = rna[:, selected_genes].copy()
    genes = _gene_table(rna_selected)
    genes["is_tf"] = genes["gene"].astype(str).isin(eligible_tfs)
    peaks = _peak_table(atac)
    if build_regulatory_candidates:
        peak_tf = peak_tf_links(peaks, motif_bed, tfs=eligible_tfs)
    else:
        peak_tf = pd.DataFrame(
            columns=["tf", "peak", "weight", "motif_score", "overlap_bp", "pvalue"]
        )
    coordinate_columns = ["chrom", "chromStart", "chromEnd", "strand"]
    coordinate_mask = genes[coordinate_columns].notna().all(axis=1)
    annotated_genes = genes.loc[coordinate_mask].copy()
    gene_peak = (
        gene_peak_prior(
            annotated_genes,
            peaks,
            gene_region=gene_region,
            promoter_len=promoter_len,
            extend_range=extend_range,
            max_genes_per_peak=max_genes_per_peak,
        )
        if build_regulatory_candidates
        else pd.DataFrame(columns=["gene", "peak", "dist", "weight", "sign"])
    )
    tf_gene = (
        tf_gene_prior(peak_tf, gene_peak)
        if build_regulatory_candidates
        else pd.DataFrame(columns=["tf", "gene", "weight"])
    )
    motif = _motif_matrix(peak_tf, atac.var_names, eligible_tfs)

    counts = rna_selected.layers["counts"]
    atac_binary = sparse.csr_matrix(atac.X > 0, dtype=np.float32)
    state_factors = MultiomeFactors(
        rna_norm=rna_selected.layers[RNA_LOG_NORMALIZED_LAYER].copy(),
        atac_tfidf=tfidf_seurat(atac.X),
        rna_cell_scores=np.ascontiguousarray(rna_selected.obsm["X_pca"], dtype=np.float32),
        rna_feature_loadings=np.ascontiguousarray(rna_selected.varm["PCs"], dtype=np.float32),
        atac_cell_scores=np.ascontiguousarray(atac.obsm["X_lsi"], dtype=np.float32),
        atac_feature_loadings=np.ascontiguousarray(atac.varm["LSI_loadings"], dtype=np.float32),
        rna_highly_variable=np.asarray(rna_selected.var["highly_variable"], dtype=bool),
        atac_highly_variable=np.asarray(atac.var["highly_variable"], dtype=bool),
        atac_binary=atac_binary,
        atac_lsi_first_library_size_correlation=float(
            atac.uns["herta_preprocessing"]["lsi"][
                "first_component_library_size_correlation"
            ]
        ),
        atac_library_size=np.asarray(
            sparse.csr_matrix(atac.X).sum(axis=1)
        ).ravel().astype(np.float64),
    )
    multiome = MultiomeData(
        rna=counts.copy(),
        atac=atac.X.copy(),
        cell_types=None if cell_type_key is None else rna.obs[cell_type_key].astype(str).to_numpy(),
        genes=genes,
        peaks=peaks,
        tf_names=eligible_tfs.astype(str).tolist(),
        motif=motif,
        motif_activity=None,
        cell_names=rna.obs_names.astype(str).tolist(),
    )
    metadata: dict[str, object] = {
        "rna": rna,
        "atac": atac,
        "state_factors": state_factors,
        "motif_bed": motif_bed,
        "tf_list": tf_table,
        "genome_build": str(genome_build),
        "gene_peak": gene_peak,
        "peak_tf": peak_tf,
        "tf_gene": tf_gene,
        "regulatory_candidates_built": bool(build_regulatory_candidates),
        "motif_tf_source": (
            "provided_unique_tf_names" if motif_tf_names is not None else "genomic_intervals"
        ),
        "hvg_gene_peak": hvg_gene_peak,
        "peak_filter_audit": peak_filter_audit,
        "tf_universe_audit": {
            "definition": "hvg_budget_union_motif_supported_rna_tf",
            "n_motif_rna_overlap": int(len(eligible_tfs)),
            "n_retained": int(genes["is_tf"].sum()),
            "n_hvg_requested": int(n_genes),
            "n_hvg_retained": int(
                np.asarray(rna_selected.var["highly_variable"], dtype=bool).sum()
            ),
            "n_non_hvg_tf_retained": int(
                (
                    genes["is_tf"].to_numpy(dtype=bool)
                    & ~np.asarray(rna_selected.var["highly_variable"], dtype=bool)
                ).sum()
            ),
            "n_all_zero_tf": int(
                (
                    np.asarray(sparse.csr_matrix(counts)[:, genes["is_tf"].to_numpy(dtype=bool)].getnnz(axis=0)).ravel()
                    == 0
                ).sum()
            ),
            "n_without_gtf_coordinates": int(
                (~coordinate_mask & genes["is_tf"].to_numpy(dtype=bool)).sum()
            ),
            "legacy_n_tfs_ignored": None if n_tfs is None else int(n_tfs),
            "requested_n_genes": int(n_genes),
            "selected_n_genes": int(len(selected_genes)),
        },
    }
    hvg_mask = np.asarray(rna_selected.var["highly_variable"], dtype=bool)
    tf_mask = np.asarray(genes["is_tf"], dtype=bool)
    universe_audit = {
        "n_cells": int(multiome.rna.shape[0]),
        "n_input_genes": n_input_genes,
        "n_hvg": int(hvg_mask.sum()),
        "n_eligible_tf": int(len(eligible_tfs)),
        "n_non_hvg_tf_retained": int((tf_mask & ~hvg_mask).sum()),
        "n_final_genes": int(multiome.rna.shape[1]),
        "n_input_peaks": n_input_peaks,
        "n_support_pass_peaks": int(peak_filter_audit["n_support_pass"]),
        "n_variable_peaks": int(multiome.atac.shape[1]),
        "n_final_peaks": int(multiome.atac.shape[1]),
    }
    metadata["universe_audit"] = universe_audit
    metadata["preprocessing_audit"] = {
        "rna_pca_fit_count": 1,
        "atac_lsi_fit_count": int(peak_filter_audit["lsi_fit_count"]),
        "hvg_selection_count": 1,
        "peak_selection_count": 1,
    }
    return multiome, metadata


def load_chen_anndata(
    rna_path: str | Path,
    atac_path: str | Path,
    n_cells: int | None = None,
    n_peaks: int | None = None,
    random_state: int = 1,
) -> tuple[AnnData, AnnData]:
    """Load Chen-2019 data using its RNA/ATAC barcode suffix convention."""

    rna, atac = load_multiome_anndata(
        rna_path,
        atac_path,
        pairing="intersection",
        rna_suffix_pattern=r"_RNA$",
        atac_suffix_pattern=r"_ATAC$",
        n_cells=n_cells,
        n_peaks=n_peaks,
        random_state=random_state,
    )
    if "cell_type" in rna.obs and "cell_type" in atac.obs:
        mismatch = (
            rna.obs["cell_type"].astype(str).to_numpy()
            != atac.obs["cell_type"].astype(str).to_numpy()
        )
        if mismatch.any():
            raise ValueError(
                f"Cell-type labels disagree for {int(mismatch.sum())} paired cells."
            )
    return rna, atac


def prepare_chen_multiome(
    chen_dir: str | Path,
    n_cells: int = 1000,
    n_genes: int = 2000,
    n_tfs: int | None = None,
    n_peaks: int | None = None,
    random_state: int = 1,
    **kwargs,
) -> tuple[MultiomeData, dict[str, object]]:
    """Prepare Chen-2019 using the canonical loader and mouse defaults."""

    chen_dir = Path(chen_dir)
    rna_path = chen_dir / "Chen-2019-RNA-aligned.h5ad"
    atac_path = chen_dir / "Chen-2019-ATAC-aligned.h5ad"
    if not rna_path.exists():
        rna_path = chen_dir / "Chen-2019-RNA.h5ad"
    if not atac_path.exists():
        atac_path = chen_dir / "Chen-2019-ATAC.h5ad"
    return prepare_multiome(
        rna_path,
        atac_path,
        chen_dir / "gencode.vM25.chr_patch_hapl_scaff.annotation.gtf.gz",
        chen_dir / "JASPAR2022-mm10.bed.gz",
        genome_build="mm10",
        motif_source_version="JASPAR2022",
        pairing="intersection",
        rna_suffix_pattern=r"_RNA$",
        atac_suffix_pattern=r"_ATAC$",
        n_cells=n_cells,
        n_genes=n_genes,
        n_tfs=n_tfs,
        n_peaks=n_peaks,
        random_state=random_state,
        **kwargs,
    )


